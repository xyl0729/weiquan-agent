@dataclass(frozen=True, slots=True)
class ExpandedQuery:
    """扩展后的检索查询。"""

    original: str
    added_terms: tuple[str, ...]

    @property
    def text(self) -> str:
        if not self.added_terms:
            return self.original
        return self.original + " " + " ".join(self.added_terms)


def lexicon_terms(message: str) -> tuple[str, ...]:
    """返回口语词表命中后应追加的法律术语。"""
    added: list[str] = []
    for triggers, terms in _TERM_LEXICON:
        if any(trigger in message for trigger in triggers):
            added.extend(terms)
    return tuple(dict.fromkeys(added))


def corpus_vocabulary(connection: sqlite3.Connection) -> frozenset[str]:
    """本地法条正文中真实出现过的连续片段集合。

    用于校验扩展词：任何不在语料中出现的词都不会改变检索结果，
    留着只会稀释查询，直接丢弃。
    """
    rows = connection.execute("SELECT content FROM statutes").fetchall()
    return frozenset(str(row[0]) for row in rows)


def filter_terms_by_corpus(
    terms: tuple[str, ...],
    corpus: frozenset[str],
) -> tuple[str, ...]:
    """只保留在语料正文中真实出现的扩展词。"""
    return tuple(
        term
        for term in terms
        if any(term in content for content in corpus)
    )


def expand_query(
    message: str,
    *,
    extra_terms: tuple[str, ...] = (),
    corpus: frozenset[str] | None = None,
) -> ExpandedQuery:
    """构造扩展查询。

    extra_terms 供模型提供的术语使用；传入 corpus 时逐词校验，
    未在语料中出现的词一律丢弃。
    """
    candidates = lexicon_terms(message)
    if extra_terms:
        candidates = tuple(
            dict.fromkeys([*candidates, *extra_terms])
        )
    if corpus is not None:
        candidates = filter_terms_by_corpus(candidates, corpus)
    return ExpandedQuery(original=message, added_terms=candidates)


