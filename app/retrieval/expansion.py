# 调顺序解决不了这个问题：真正的医疗纠纷也常提到吃药、不舒服，
# 把食品组整体提前会反过来劫走医疗案情。所以用共现判定。
_FOOD_SOURCE_WORDS = (
    "外卖",
    "点的菜",
    "餐厅",
    "饭店",
    "食堂",
    "这顿饭",
    "吃的东西",
    "买的食品",
    "买的菜",
    "奶茶",
    "蛋糕",
)
_FOOD_ILLNESS_WORDS = (
    "上吐下泻",
    "拉肚子",
    "腹泻",
    "食物中毒",
    "吃完就",
    "吃了以后",
    "吃完不舒服",
    "肚子疼",
    "呕吐",
)


# 借车、租车出事故：借贷词与车辆词共现时判为机动车责任。
# 子串匹配处理不了「我借了朋友的车」——「借了」和「车」之间隔着字，
# 拼不出固定触发词，而「借了」又会被借贷组先抢走。
_LEND_WORDS = ("借", "租")
_VEHICLE_WORDS = ("车", "机动车", "驾驶")
_ACCIDENT_WORDS = ("事故", "撞", "肇事", "追尾", "赔", "责任", "出事")


def infer_topic(message: str) -> str | None:
    """按口语触发词推断纠纷主题，供精选依据映射使用。

    返回的是 GENERAL_BASIS_REFS 的键；调用方据此取人工确认过的条文，
    而不是让 BM25 直接挑条文。命中不了就返回 None，宁可不给依据。
    """
    # 共现判定必须在词表循环之前：借贷组排在交通事故组之后，
    # 靠调整顺序解决不了「借了…车」这种跨字组合。
    if any(word in message for word in _FOOD_SOURCE_WORDS) and any(
        word in message for word in _FOOD_ILLNESS_WORDS
    ):
        return "logistics_travel_food"
    if (
        any(word in message for word in _LEND_WORDS)
        and any(word in message for word in _VEHICLE_WORDS)
        and any(word in message for word in _ACCIDENT_WORDS)
    ):
        return "traffic_accident"
    for topic_id, triggers in _TOPIC_TRIGGERS:
        if any(trigger in message for trigger in triggers):
            return topic_id
    return None
